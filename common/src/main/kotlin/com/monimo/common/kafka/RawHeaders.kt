package com.monimo.common.kafka

// raw 토픽 메시지의 봉투 메모(Kafka 헤더) 이름. 수집기가 붙이고 적재 처리기가 꺼낸다.
//
// 값(protobuf 바이트)은 한 글자도 건드리지 않는다는 약속(ADR `#16` · `#65`)을 지키면서 수집기만 아는 사실을
// 적재 처리기까지 옮기는 자리다. 지금은 보낸 쪽 주소 하나뿐이다.
//
// 여기 두는 이유 : 붙이는 쪽(수집기)과 꺼내는 쪽(적재 처리기)이 다른 모듈이라 글자가 어긋나면
// 조용히 빈칸이 된다. `RawSignal` 의 토픽 이름 · 키와 같은 이유로 공통 모듈에 둔다.
object RawHeaders {

    // 연결 상대(에이전트가 붙은 파드)의 주소. OTel 의미 규약의 Stable 속성 이름을 그대로 쓴다.
    //
    // client.address 가 아닌 이유 (ADR `#63`) : 그쪽 규약 주석은 "중간에 프록시가 있으면 그 뒤에 숨은
    // 원래 클라이언트를 가리켜야 한다" 고 적혀 있다. 헤더를 파싱해 복원하는 것이 전제인데 우리는
    // 소켓에서 직접 읽으므로 지키지 못할 약속이 된다. network.peer.address 는 "방금 연결한 그 상대" 라서
    // 우리가 담는 값과 뜻이 정확히 같다.
    // 짝 속성 network.peer.port 는 담지 않는다. 명부에 포트 칸이 없다
    const val PEER_ADDRESS = "network.peer.address"
}
